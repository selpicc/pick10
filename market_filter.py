# ─────────────────────────────────────────────────────────────────
# 띄어쓰기 변형 자동 생성 (한국어 합성어 처리)
# 예: "튼살크림" ↔ "튼살 크림", "스트레치마크" ↔ "스트레치 마크"
# 사용처: collect_5.py의 [5-1.6] 메인 라인 매칭 풀 구성
# ─────────────────────────────────────────────────────────────────
def generate_space_variants(keyword: str) -> set:
    """한국어 키워드의 띄어쓰기 변형 자동 생성.

    예시:
      "튼살크림"       → {"튼살크림", "튼살 크림"}
      "스트레치마크"   → {"스트레치마크", "스트 레치마크",
                          "스트레 치마크", "스트레치 마크"}
      "임산부튼살크림" → {"임산부튼살크림", "임산 부튼살크림",
                          "임산부 튼살크림", "임산부튼 살크림",
                          "임산부튼살 크림"}

    전략:
      1. 원본 + 공백 제거 버전
      2. 공백 제거 후 모든 2분할 변형 (각 부분 2자 이상)

    의미없는 분할도 일부 포함되지만, substring 매칭이라 큰 문제 X
    (예: "임산 부튼살크림"은 매칭 가능성 거의 없음)
    """
    keyword = (keyword or "").strip()
    if not keyword:
        return set()

    variants = {keyword}
    no_space = keyword.replace(" ", "")
    if len(no_space) >= 2:
        variants.add(no_space)

    # 공백 제거된 형태에서 모든 가능한 2분할 변형 생성
    # 각 부분이 2자 이상이어야 의미있는 매칭 가능
    for split_at in range(2, len(no_space) - 1):
        left = no_space[:split_at]
        right = no_space[split_at:]
        if len(left) >= 2 and len(right) >= 2:
            variants.add(f"{left} {right}")

    return variants


