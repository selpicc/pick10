def market_fit_check(brand_name: str, product_title: str) -> tuple:
    """3중 크로스체크 (A+B+C) — "우리 시장 우선 통과" 정책.
    매칭 범위: 브랜드명 + 상품명 (소문자 비교)

    검사 순서 (2026-05-13 변경):
      B(대기업) → A(영유아/임산부) → C(부정)
      → 영유아/임산부 키워드가 있으면 즉시 통과 (부정 키워드 무시)
      → 예: "산후맘 살균제" — 우리 시장 안에 있는 제품으로 인정

    이전 순서 B → C → A 의 문제:
      "살균/소독" 같은 부정 키워드가 산모용 위생용품 등 합법적 우리 시장
      후보를 false negative로 탈락시켰음.

    반환: (태그, 사유)
        ("ok", "")            — 통과
        ("a", reason)         — A 탈락 (영유아/임산부 키워드 X + 부정 키워드 X)
        ("b", reason)         — B 탈락 (대기업)
        ("c", reason)         — C 탈락 (우리 시장 키워드 X + 부정 키워드 매칭)
    """
    text = f"{brand_name} {product_title}".lower()

    # B. 대기업 명단 검사 (확실한 컷 — 우리 시장이어도 대기업은 제외)
    for big in BIG_COMPANY_BLOCKLIST:
        if big.lower() in text:
            return "b", f"대기업: {big}"

    # A. 영유아/임산부 시장 키워드 검사 (우리 시장 안에 있으면 즉시 통과)
    # ⭐ C 검사보다 먼저! — 우리 시장 후보는 부정 키워드 있어도 통과
    # 예: "산후맘 살균제" → '산후' 매칭 → OK (살균 검사 안 함)
    for tk in MARKET_FIT_KEYWORDS:
        if tk.lower() in text:
            return "ok", ""

    # C. 부정 키워드 검사 (A 매칭 안 된 후보만 — 명백히 다른 시장)
    for neg in NEGATIVE_KEYWORDS:
        if neg.lower() in text:
            return "c", f"다른 시장: {neg}"

    return "a", "영유아 시장 키워드 X"


