    """수동 큐레이션 + 동의어/제품 사전 자동 확장.

    예시 확장 결과 (소스별):
      CORE     → "튼살", "신생아", "임산부", ...
      SYNONYMS → "베이비", "신생아", "유아", "산모", "수유", ...
      PRODUCTS → "튼살크림", "스트레치 마크 크림", "임부 크림",
                "산양분유", "조제 분유", "팬티 기저귀", ...
    """
    extended = set(MARKET_FIT_KEYWORDS_CORE)

    # 1차: KEYWORD_SYNONYMS (영유아/임산부 동의어)
    for syn_list in KEYWORD_SYNONYMS.values():
        extended.update(syn_list)

    # 2차: PRODUCT_SYNONYMS (임산부 제품군 — 키 + 값 모두)
    for product, syns in PRODUCT_SYNONYMS.items():
        extended.add(product)
        extended.update(syns)

    # 정제: 양옆 공백 + 2자 이상만
    cleaned = set()
    for kw in extended:
        kw = (kw or "").strip()
        if len(kw) >= 2:
            cleaned.add(kw)
    return cleaned


