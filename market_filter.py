def classify_category(product_title: str) -> str:
    """주력상품명 → 10개 카테고리 중 하나로 자동 분류.

    1차: CATEGORY_KEYWORDS 정확 매칭 (정의 순서대로)
    2차: PRODUCT_HINTS + 영유아/임산부 키워드 fallback
    3차: '기타' 반환 (어떤 패턴도 매칭 X)
    """
    if not product_title:
        return "기타"
    text = product_title.lower()

    # 1차: 정확 매칭
    for category, keywords in CATEGORY_KEYWORDS.items():
        for kw in keywords:
            if kw.lower() in text:
                return category

    # 2차: 광범위 fallback
    has_mom = any(k in text for k in ["임산부", "임부", "산모", "산후"])
    has_baby = any(k in text for k in ["베이비", "유아", "신생아", "아기", "영유아", "영아"])

    if has_mom:
        # 임산부/산모 제품 → 일반 제품 키워드로 카테고리 추정
        if any(k in text for k in ["크림", "로션", "오일", "비누", "샴푸",
                                    "토너", "에센스", "마스크", "클렌징", "워시"]):
            return "임산부 뷰티"
        if any(k in text for k in ["옷", "원피스", "바지", "셔츠", "잠옷",
                                    "속옷", "양말", "코트", "자켓", "후드"]):
            return "임산부 의류"
        if any(k in text for k in ["가방", "베개"]):
            return "이동·외출"
        if any(k in text for k in ["영양", "비타민", "엽산"]):
            return "임산부 영양제"
        # 임산부 키워드만 있고 제품 모호 → 임산부 뷰티로 (가장 일반적)
        return "임산부 뷰티"

    if has_baby:
        # 베이비/유아 제품 → 일반 제품 키워드로 카테고리 추정
        for cat, hints in PRODUCT_HINTS.items():
            if cat in {"임산부 뷰티", "임산부 의류"}:
                continue
            for hint in hints:
                if hint in text:
                    return cat
        # 베이비 키워드만 있고 제품 모호 → 베이비 스킨케어로 (가장 일반적)
        return "베이비 스킨케어"

    # 3차: 어떤 패턴도 매칭 X → 기타
    return "기타"
